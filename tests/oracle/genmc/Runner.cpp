/*
 * kater-oracle-runner: the GenMC side of `kater-oracle genmc`. It turns
 * graphs into GenMC execution graphs and asks the consistency checker that
 * Kater exported for a model about them. It links GenMC and no Kater code
 * (the two define the same global names), so the comparison with the
 * reference semantics happens in kater-oracle, which talks to it through
 * a pipe:
 *
 *   kater-oracle-runner MODEL
 *
 * A request is a graph in the form Execution::print() renders, between the
 * lines "graph" and "end", then queries, one per line, then "go":
 *
 *   consistent        isConsistent(G)
 *   relinche          isCoherentRelinche(G), with lin added last, as Relinche does
 *   incremental E     isConsistent(E), with E added last, as GenMC adds it
 *   views             every view of every event
 *   prefix            calculatePrefixView() of every event
 *   rprefix           calculateRevisitPrefixView() of every event
 *   stores R          getCoherentStores(R), with R added last, before its rf
 *   placings W        getCoherentPlacings(W), with W added last, before co
 *   revisits W R...   filterCoherentRevisits(W, [R...]), with W added last
 *
 * The answers come in the same order, then "done". Events are named by
 * their number in the graph; the initial writes by "init".
 */

